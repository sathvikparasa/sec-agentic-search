"""Compute gold answers from the dataset: evals/questions_src.yaml -> evals/questions.yaml.

    docker compose exec app python -m evals.build_gold

Every numeric/ranking answer comes from running the question's gold_sql; the query is stored
next to the answer. Text gold chunk ids are drafts (needs_review: true). For questions marked
single_tag_trap, it also runs the same query with revenue taken from only one tag
(RevenueFromContractWithCustomerExcludingAssessedTax) and confirms that answer is wrong.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

import psycopg
import yaml

DSN = os.environ.get("DATABASE_URL", "postgresql://mcp_reader:mcp_reader@db:5432/edgar")
HERE = Path(__file__).resolve().parent
SINGLE_TAG = ("(SELECT ticker, period_type, fiscal_year, value, id AS fact_id FROM facts "
              "WHERE concept = 'RevenueFromContractWithCustomerExcludingAssessedTax' AND unit = 'USD')")


def to_num(v):
    f = float(v)
    return int(f) if f.is_integer() else f


def single_tag(sql: str) -> str:
    # FROM revenue a / JOIN revenue b / FROM revenue r  ->  one-tag subquery
    return re.sub(r"\b(FROM|JOIN)\s+revenue\b(\s+(?!WHERE|ORDER|JOIN|ON)\w+)?",
                  lambda m: f"{m.group(1)} {SINGLE_TAG} {(m.group(2) or ' revenue').strip()}", sql)


class _Literal(str):
    pass


yaml.add_representer(_Literal, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def main() -> None:
    src = yaml.safe_load((HERE / "questions_src.yaml").read_text())["questions"]
    out, problems = [], []
    with psycopg.connect(DSN) as conn:
        def facts_for(ids):
            rows = conn.execute("SELECT id, ticker, concept, value, fiscal_year FROM facts WHERE id = ANY(%s)",
                                (list(ids),)).fetchall()
            return [{"fact_id": r[0], "ticker": r[1], "concept": r[2], "value": to_num(r[3]),
                     "fiscal_year": r[4]} for r in rows]

        for q in src:
            cat = q["category"]
            gold: dict = {}
            if "gold_sql" in q:
                gold["sql"] = _Literal(q["gold_sql"].strip() + "\n")
                rows = conn.execute(q["gold_sql"]).fetchall()
                if not rows:
                    problems.append(f"{q['id']}: gold_sql returned no rows")
                    continue
                if cat == "numeric" or (cat == "hybrid" and "top_n" not in q):
                    value, ids = rows[0][0], rows[0][1]
                    if len(rows) != 1:
                        problems.append(f"{q['id']}: expected 1 row, got {len(rows)}")
                    gold |= {"value": to_num(value), "rel_tol": q.get("rel_tol", 0.01),
                             "support": facts_for(ids)}
                else:
                    n = len(rows) if q.get("top_n") == "all" else int(q["top_n"])
                    top = rows[:n]
                    gold |= {"tickers": [r[0] for r in top], "top_n": n,
                             "metrics": {r[0]: to_num(r[1]) for r in rows[: n + 2]},
                             "support": facts_for({i for r in top[:1] for i in r[2]})}
                    if n < len(rows) and rows[n - 1][1] == rows[n][1]:
                        problems.append(f"{q['id']}: tie at position {n}")
                    if q.get("single_tag_trap"):
                        alt = conn.execute(single_tag(q["gold_sql"])).fetchall()
                        alt_top = [r[0] for r in alt[:n]]
                        gold["single_tag_answer"] = alt_top
                        if alt_top == gold["tickers"]:
                            problems.append(f"{q['id']}: marked single_tag_trap but one-tag query gives the same answer")
                if q.get("text_from") == "top1":
                    gold["top_ticker"] = rows[0][0]
                    if q.get("ticker") != rows[0][0]:
                        problems.append(f"{q['id']}: SQL winner is {rows[0][0]} but text gold is for {q.get('ticker')}")
            if cat in ("text", "hybrid"):
                for k in ("ticker", "form", "must_mention", "notes"):
                    if k in q:
                        gold[k] = q[k]
                if "gold_chunks_sql" in q:
                    gold["gold_chunks_sql"] = _Literal(q["gold_chunks_sql"].strip() + "\n")
                    gold["gold_chunk_ids"] = [r[0] for r in conn.execute(q["gold_chunks_sql"]).fetchall()]
                    if not gold["gold_chunk_ids"]:
                        problems.append(f"{q['id']}: gold_chunks_sql found no chunks")
                if "must_mention" not in gold:
                    problems.append(f"{q['id']}: text part has no must_mention")
                gold["needs_review"] = True
            out.append({"id": q["id"], "category": cat, "question": q["question"], "gold": gold})

    header = ("# GENERATED by evals/build_gold.py from questions_src.yaml. Do not edit by hand.\n"
              "# Numeric/ranking gold = result of gold.sql on the dataset. Text gold chunks: needs_review.\n")
    (HERE / "questions.yaml").write_text(header + yaml.dump({"questions": out}, sort_keys=False,
                                                            allow_unicode=True, width=110))
    print(f"wrote {len(out)} questions to evals/questions.yaml")
    for q in out:
        g = q["gold"]
        ans = g.get("value", g.get("tickers"))
        extra = f"  (one-tag query: {g['single_tag_answer']})" if "single_tag_answer" in g else ""
        chunks = f"  chunks={len(g['gold_chunk_ids'])}" if "gold_chunk_ids" in g else ""
        print(f"  {q['id']} {q['category']:8} {ans}{extra}{chunks}")
    if problems:
        print("\nPROBLEMS:")
        for p in problems:
            print("  -", p)


if __name__ == "__main__":
    main()
